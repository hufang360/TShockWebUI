export const dicts: Record<Lang, Dict> = { zh, en }

/** 非组件场景（如 App 构造 banner）也可用的翻译函数。 */
export function translate(
  lang: Lang,
  key: string,
  vars?: Record<string, string | number>,
): string {
  const dict = dicts[lang] ?? zh
  let s = dict[key] ?? zh[key] ?? key
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.replaceAll(`{${k}}`, String(v))
    }
  }
  return s
}

export interface I18n {
  lang: Lang
  t: (key: string, vars?: Record<string, string | number>) => string
}

const fallback: I18n = {
  lang: 'zh',
  t: (key) => key,
}

const I18nContext = createContext<I18n>(fallback)

export function I18nProvider({ lang, children }: { lang: Lang; children: ReactNode }) {
  const value = useMemo<I18n>(
    () => ({ lang, t: (key, vars) => translate(lang, key, vars) }),
    [lang],
  )
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n(): I18n {
  return useContext(I18nContext)
}
