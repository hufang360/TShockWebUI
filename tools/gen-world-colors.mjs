#!/usr/bin/env node
/**
 * gen-world-colors.mjs —— 生成 web/src/lib/save/worldColors.generated.ts
 * （「查看世界」缩略图用的图格 / 墙 / 区域颜色；纯前端渲染，不经服务器）。
 *
 * 数据来源（不手工编造，可重复生成）：
 *   - `TEDIT_DIR/src/TEdit/MapColors.xml`：TEdit 随仓库提供的**游戏内小地图颜色表**
 *     （文件头写明 "Terraria MapColors.XML Specifications ... Current Game Ver: Terraria 1.4.5.0"）。
 *     每个 Id 有多条 Paint 变体，这里只取 `Paint="0"`（未上漆）作为基础色；同 Id 第一条胜出（SubID=0）。
 *     出处与核实记录见 docs/技术事实.md「世界文件（.wld）」。
 *   - 区域背景色（Space/Sky/Earth/Rock/Hell）与液体色取自 `TEDIT_DIR/docs/settings.xml` 的
 *     `<GlobalColors>`（TEdit 的来源同上：游戏内小地图背景）。XML 缺失时用内置同值兜底。
 *
 * 输出：TS 模块里的 `Uint32Array`（索引 = ID，值 = 0xRRGGBB），随前端打包，无运行期文件 IO。
 *
 * 运行：
 *   TEDIT_DIR=../TEdit node tools/gen-world-colors.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const TEDIT_DIR = process.env.TEDIT_DIR || join(HERE, '..', '..', 'TEdit');
const OUT = process.env.OUT || join(HERE, '..', 'web', 'src', 'lib', 'save', 'worldColors.generated.ts');

// 与 settings.xml 的 <GlobalColors> 一致（TEdit 缺失时兜底）。
const ZONE_FALLBACK = {
  Space: '#336699',
  Sky: '#9BD1FF',
  Earth: '#54392A',
  Rock: '#484039',
  Hell: '#330000',
};

const xml = readFileSync(join(TEDIT_DIR, 'src', 'TEdit', 'MapColors.xml'), 'utf8');

/** #AARRGGBB -> 0xRRGGBB（丢弃 alpha：颜色表里 tile/wall 一律不透明）。 */
function parseColor(hex) {
  const m = /^#([0-9a-fA-F]{2})([0-9a-fA-F]{6})$/.exec(hex.trim());
  if (!m) throw new Error(`无法解析颜色：${hex}`);
  return parseInt(m[2], 16);
}

/** 抽取 <Tiles> / <Walls> 下 Paint="0" 的条目（同 Id 第一条胜出）。 */
function collect(tag) {
  const section = new RegExp(`<${tag}s>([\\s\\S]*?)</${tag}s>`).exec(xml);
  if (!section) throw new Error(`MapColors.xml 缺少 <${tag}s> 段`);
  const map = new Map();
  for (const m of section[1].matchAll(new RegExp(`<${tag}\\b[^>]*?\\bId="(\\d+)"[^>]*?\\bPaint="0"[^>]*?\\bColor="(#[0-9A-Fa-f]+)"`, 'g'))) {
    const id = Number(m[1]);
    if (!map.has(id)) map.set(id, parseColor(m[2]));
  }
  return map;
}

const tiles = collect('Tile');
const walls = collect('Wall');

/**
 * MapColors.xml（1.4.5.0）之后新增图格的补充，来源是**游戏自己的** `MapHelper.Initialize`：
 *
 * - 753（GiantTiki）：游戏写的是 `array[753][0] = MultiplyMapColor(array[158][0], 0.95f)`，
 *   所以按 158 的颜色 ×0.95 算（Terraria.Map/MapHelper.cs:1271）。
 * - 127 / 135 / 210 / 428 / 504 / 541：游戏**没有给它们图格颜色**（MapHelper 里只有墙色 `array4`，
 *   或完全没赋值），地图上本来就不可见。这里**故意不填**（0）→ 渲染时退回中性灰，
 *   比"整块透明看不见"更有用；这条已在 docs/TODO.md P6 与 docs/技术功能文档里写明。
 */
const TILE_COLOR_OVERRIDES = () => {
  const map = new Map(tiles);
  const t158 = tiles.get(158);
  if (t158 != null) {
    // MultiplyMapColor：逐通道 × 0.95（游戏的 Color 乘法语义）
    const ch = (v) => Math.min(255, Math.round(v * 0.95));
    const r = ch((t158 >> 16) & 0xff);
    const g = ch((t158 >> 8) & 0xff);
    const b = ch(t158 & 0xff);
    map.set(753, (r << 16) | (g << 8) | b);
  }
  return map;
};
const tilesWithOverrides = TILE_COLOR_OVERRIDES();

/** 游戏里没有图格颜色、由我们兜底成中性灰的 ID（写进文件头注释，方便以后核对）。 */
const FALLBACK_GRAY_TILES = [127, 135, 210, 428, 504, 541];

/** 区域背景色：优先读 docs/settings.xml 的 GlobalColors。 */
function zoneColors() {
  let values = ZONE_FALLBACK;
  try {
    const settings = readFileSync(join(TEDIT_DIR, 'docs', 'settings.xml'), 'utf8');
    const found = {};
    for (const m of settings.matchAll(/<GlobalColor Name="(\w+)" Color="(#[0-9A-Fa-f]+)"\s*\/>/g)) {
      if (m[1] in ZONE_FALLBACK) found[m[1]] = m[2];
    }
    if (Object.keys(found).length === Object.keys(ZONE_FALLBACK).length) values = found;
  } catch {
    // 缺 settings.xml 时用兜底值。
  }
  return Object.entries(ZONE_FALLBACK).map(([name, fallback]) => [name, parseColor(values[name] ?? fallback)]);
}

const tileSize = Math.max(...tilesWithOverrides.keys()) + 1;
const wallSize = Math.max(...walls.keys()) + 1;
const zones = zoneColors();

const fmt = (v) => `0x${v.toString(16).padStart(6, '0')}`;
const arr = (map, size) => {
  const rows = [];
  for (let i = 0; i < size; i += 12) {
    const row = [];
    for (let j = i; j < Math.min(i + 12, size); j++) row.push(fmt(map.get(j) ?? 0));
    rows.push('  ' + row.join(', ') + ',');
  }
  return rows.join('\n');
};

const ts = `// Code generated by tools/gen-world-colors.mjs. DO NOT EDIT.
//
// 「查看世界」缩略图颜色表：索引 = 图格 / 墙 ID，值 = 0xRRGGBB（0 = 颜色表里没有该 ID）。
// 来源：TEdit 仓库 src/TEdit/MapColors.xml（Paint=0 基础色）+ docs/settings.xml 的 GlobalColors，
// 并向游戏源码 MapHelper.Initialize 补齐了 MapColors.xml 之后新增的图格（如 753 = 158 × 0.95）。
// 游戏本身没给颜色的图格（${FALLBACK_GRAY_TILES.join(' / ')}）保持 0 → 渲染时用中性灰兜底。
// 出处与核实见 docs/技术事实.md「世界文件（.wld）」。

/** 图格 ID → 小地图颜色。 */
export const TILE_COLORS = new Uint32Array([
${arr(tilesWithOverrides, tileSize)}
])

/** 墙 ID → 小地图颜色。 */
export const WALL_COLORS = new Uint32Array([
${arr(walls, wallSize)}
])

/** 深度分区背景色（太空 / 天空 / 地表 / 岩石层 / 地狱）。 */
export const ZONE_COLORS = {
${zones.map(([name, v]) => `  ${name.toLowerCase()}: ${fmt(v)},`).join('\n')}
} as const
`;

writeFileSync(OUT, ts);
console.log(
  `wrote ${OUT}\n  tiles=${tilesWithOverrides.size}/${tileSize} walls=${walls.size}/${wallSize} zones=${zones.length}`,
);
